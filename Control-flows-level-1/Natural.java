import java.util.Scanner;
class Natural {
public static void main(String args[]){
 Scanner sc=new Scanner(System.in);
 System.out.println("Enter a no:-");
 int n=sc.nextInt();
 if(n>0){
 int a=n*(n+1)/2;
 System.out.println("The sum of n natural number is:" +a);
 }
 else{
 System.out.println("The sum of n is not natural number:" +a);
 }
 }
 }
 
 
 